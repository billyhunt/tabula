#!/usr/bin/env node
/**
 * Writes licenses/THIRD_PARTY_LICENSES.txt: the licence text (and NOTICE file,
 * where one exists) of every production dependency bundled into Tabula.
 *
 * Generated rather than hand-kept because Excalidraw alone pulls in ~290
 * packages, and MIT, ISC, BSD and Apache-2.0 all require their notice to
 * travel with redistributed copies. Runs before packaging; fails loudly if a
 * package has neither a licence file nor a known override, so a new
 * dependency cannot slip into a build without its notice.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

// Packages that ship no licence file in their npm tarball, mapped to the
// upstream licence text kept in licenses/. Keys ending in / match a scope.
const OVERRIDES = {
  '@excalidraw/fractional-indexing': 'licenses/CC0-fractional-indexing.txt',
  '@excalidraw/': 'licenses/MIT-excalidraw.txt',
  '@radix-ui/': 'licenses/MIT-radix-ui.txt',
  fastdom: 'licenses/MIT-fastdom.txt',
  strictdom: 'licenses/MIT-strictdom.txt',
  'react-remove-scroll-bar': 'licenses/MIT-react-remove-scroll-bar.txt',
}

const overrideFor = (name) =>
  OVERRIDES[name] ??
  Object.entries(OVERRIDES).find(([k]) => k.endsWith('/') && name.startsWith(k))?.[1]

const LICENSE_FILE = /^(licen[cs]e|copying)(\b|[-_.]|$)/i
const NOTICE_FILE = /^notice(\b|[-_.]|$)/i

const packages = JSON.parse(
  execFileSync('npm', ['query', '.prod'], { cwd: root, encoding: 'utf8', maxBuffer: 64 << 20 }),
)

const seen = new Set()
const sections = []
const missing = []

for (const pkg of packages.sort((a, b) => a.name.localeCompare(b.name))) {
  const key = `${pkg.name}@${pkg.version}`
  // Tabula itself.
  if (!pkg.location) continue
  if (seen.has(key)) continue
  seen.add(key)

  const dir = path.join(root, pkg.location)
  const files = existsSync(dir) ? readdirSync(dir) : []
  const texts = files
    .filter((f) => LICENSE_FILE.test(f) || NOTICE_FILE.test(f))
    .sort()
    .map((f) => readFileSync(path.join(dir, f), 'utf8').trim())

  const override = overrideFor(pkg.name)
  if (texts.length === 0 && override) {
    texts.push(readFileSync(path.join(root, override), 'utf8').trim())
  }
  const declared = typeof pkg.license === 'object' ? pkg.license?.type : pkg.license
  if (texts.length === 0) {
    missing.push(`${key} (${declared ?? 'no licence declared'})`)
    continue
  }
  sections.push(`${'='.repeat(78)}\n${key} — ${declared ?? 'see text'}\n${'='.repeat(78)}\n\n${texts.join('\n\n---\n\n')}\n`)
}

if (missing.length) {
  console.error(`No licence text found for:\n  ${missing.join('\n  ')}`)
  console.error('Add the upstream licence to licenses/ and map it in OVERRIDES.')
  process.exit(1)
}

const header =
  'Third-party software bundled with Tabula.\n' +
  'Generated by scripts/collect-licenses.mjs; do not edit by hand.\n' +
  `${sections.length} packages.\n\n`
writeFileSync(path.join(root, 'licenses/THIRD_PARTY_LICENSES.txt'), header + sections.join('\n'))
console.log(`Wrote licence texts for ${sections.length} packages.`)
